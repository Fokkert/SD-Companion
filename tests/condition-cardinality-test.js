const fs = require('fs'), vm = require('vm'), assert = require('assert');
globalThis.SDCompanion = {};
vm.runInThisContext(fs.readFileSync('src/shared/condition-registry.js', 'utf8'));
const R = SDCompanion.ConditionRegistry;
let c = { field: 'project', operator: 'equals', values: ['IT', 'HR'], value: '' };
R.normalizeCondition(c);
assert.equal(R.valueMode(c.field, c.operator), 'single');
assert.deepEqual(c.values, []);
assert.equal(c.value, 'IT');
assert.deepEqual(R.conditionValues(c), ['IT']);
c = { field: 'project', operator: 'is-any-of', values: [], value: 'IT' };
R.normalizeCondition(c);
assert.equal(R.valueMode(c.field, c.operator), 'multi');
assert.deepEqual(c.values, ['IT']);
assert.equal(c.value, '');
c = { field: 'project', operator: 'exists', values: ['IT'], value: 'HR' };
R.normalizeCondition(c);
assert.deepEqual(R.conditionValues(c), []);
assert.deepEqual(c.values, []);
assert.equal(c.value, '');
c = { field: 'label', operator: 'contains-all', values: ['vip', 'urgent'], value: '' };
R.normalizeCondition(c);
assert.equal(R.valueMode(c.field, c.operator), 'multi');
assert.deepEqual(R.conditionValues(c), ['vip', 'urgent']);
console.log('condition-cardinality-test: OK');

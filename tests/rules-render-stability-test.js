const fs = require('fs'), vm = require('vm'), assert = require('assert');
globalThis.crypto = require('crypto').webcrypto;
globalThis.SDCompanion = {};
for (const f of ['src/shared/constants.js', 'src/shared/utils.js', 'src/shared/schedule.js', 'src/shared/condition-registry.js', 'src/shared/rule-query.js', 'src/shared/defaults.js']) vm.runInThisContext(fs.readFileSync(f, 'utf8'), { filename: f });
vm.runInThisContext(fs.readFileSync('src/ui/app/app-core.js', 'utf8'), { filename: 'app-core' });
const SD = SDCompanion, A = SDApp;
const site = SD.Defaults.site({ baseUrl: 'https://jira.example.test', name: 'Jira' }),
  profile = SD.Defaults.profile('P', site);
site.projects = [{ id: '10', key: 'IT', name: 'IT' }];
site.issueTypes = [{ id: '100', name: 'Incident', projectKey: 'IT' }];
site.statuses = [{ id: '1', name: 'Open', projectKey: 'IT', issueTypeId: '100' }];
site.users = [];
site.filters = [];
site.priorities = [];
site.resolutions = [];
site.transitionCatalog = [];
const rule = SD.Defaults.rule('Condition rule');
rule.logic.groups = [{ id: 'g', operator: 'AND', negate: false, conditions: [{ id: 'c1', field: 'issueType', operator: 'is-any-of', values: ['100'] }, { id: 'c2', field: 'status', operator: 'is-any-of', values: ['1'] }] }];
profile.rules = [rule];
A.state = { jiraSites: [site], profiles: [profile], activeSiteId: site.id, activeProfileId: profile.id, appearance: {}, system: {}, runtime: {} };
for (const f of ['src/ui/app/pages/base.js', 'src/ui/app/pages/rule-conditions.js', 'src/ui/app/pages/rule-actions.js', 'src/ui/app/pages/rules.js']) vm.runInThisContext(fs.readFileSync(f, 'utf8'), { filename: f });
A.beginRuleEdit(rule);
A.ruleEditorSection = 'setup';
let html = A.pageRules();
assert(!html.includes('Effective JQL'));
assert(html.includes('Save Rule'));
A.ruleEditorSection = 'conditions';
html = A.pageRules();
assert(html.includes('Effective JQL'));
assert(html.includes('Incident'));
assert(html.includes('Open'));
assert(html.includes('Match all'));
A.ruleEditorSection = 'advanced';
html = A.pageRules();
assert(html.includes('Execution policy'));
assert(html.includes('Conflict policy'));
console.log('rules-render-stability-test: OK');
